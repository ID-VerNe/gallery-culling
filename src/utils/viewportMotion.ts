/**
 * 视口动效通道（issue #18 · PB-1）。
 *
 * 三视口原先各自写死 `<img>` 的 `transition`，值是两套（Preview 0.08s、双栏
 * 0.05s），滚轮和拖拽又共用同一条缓动 —— 滚轮打一格也要补间 50–80ms，鼠标
 * 已经在下一格了，画面还在追，读作「慢半拍」。拖拽只能靠 `isDragging` 单独
 * 关掉补间来救。
 *
 * 真正的分界不是「是否在拖」，而是输入形态：
 *
 *  - **手势通道**（`GESTURE`：拖拽、滚轮）：连续输入，每一帧都有新目标，
 *    补间只会让画面落后于指针。必须 `none`。
 *  - **跳变通道**（`SETTLE`：双击、适应/1:1 复位、± 按钮）：一次离散跳变，
 *    没有中间帧可跟，补间让空间关系可读（放大后看得出是「从哪儿推近的」）。
 *
 * 所以通道由**产生该次变化的输入**决定，而不是由「当前是否正在拖拽」决定：
 * 滚轮抬手之后 `isDragging` 已经是 false，这时再按 `isDragging` 判定就会给
 * 滚轮补间，正是原缺陷。
 *
 * 通道串是**唯一真值**：两个 hook 产出的 `transition` 都来自这里，三个视口
 * 直接读 hook 的值，不允许再各写一份字面量（`ViewportMotionChannel.test.tsx`
 * 逐字比对三视口）。
 */

/** 手势通道：连续输入，不补间。 */
export const GESTURE = 'none';

/**
 * 跳变通道：离散跳变，120ms 收尾。
 *
 * 用 `cubic-bezier(0.32, 0.72, 0, 1)`（近似 `ease-out-quint`）：起步快、尾巴
 * 长，读作「已经在融进目标位置」而不是「匀速滑过去」。120ms 是量出来的
 * —— 双击 1→2.5 倍时缩略图级别的位移在 120ms 内走完，再长就和下一次操作
 * 抢注意力。
 */
export const SETTLE = 'transform 0.12s cubic-bezier(0.32, 0.72, 0, 1)';
